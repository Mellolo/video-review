"""Prompt builder functions for VideoStoryboardEngine
(extracted from tools/storyboard_gen/video_engine.py).

Two variants:
- build_replicate_screenplay_prompt  — 复刻模式：忠实还原参考视频
- build_recreate_screenplay_prompt   — 二创模式：保留题材风格，创作全新剧情
"""


def build_replicate_screenplay_prompt(
    total_duration: float,
    drama_requirements: str,
    story_arc_output_rules: str,
    fewshot_examples: str,
    source_duration: float = 0.0,
) -> str:
    """复刻模式 system prompt。

    Response schema: ScreenplaySchema
    """
    duration_str = f"{total_duration:.1f}"
    source_duration_hint = ""
    if source_duration and source_duration > 0:
        source_duration_hint = (
            f"- 参考视频原始时长约 {source_duration:.1f} 秒，但你必须以目标总时长 {duration_str} 秒为准来组织叙事密度\n"
            "- 如果目标时长短于原视频，请压缩次要重复动作、减少无效停顿，只保留关键情节\n"
            "- 如果目标时长长于原视频，可以适度补足动作衔接、情绪推进与转场描述，但不要凭空扩写无关剧情\n"
        )

    return f"""请仔细分析这个视频的内容、风格和叙事手法，然后创作一个完整的**文字剧本**。

你的任务是写一段**连贯的故事叙述文本**（narrative 字段），不是分镜脚本。
不需要拆分成场景编号，不需要镜头角度、光线等技术细节，就写成流畅的故事。

叙述要求：
- 目标总时长约 {duration_str} 秒的视频内容量
{source_duration_hint}- 比视频内容更凝练，但保留所有核心情节和对话
- 对话用自然方式嵌入，标明说话人。例如：
  角色说的话：陈风怒喝："你休想！"
  内心独白：陈风心想（这是最后的机会了）
  路人/群众：周围人议论纷纷："这小子疯了吧？"
- 写成连贯流畅的叙述，有起承转合
- 明确交代人物状态变化、动作延续、空间方位和情绪推进，让后续分段生成的视频片段天然容易前后衔接
- 必须把视频中的高压冲突、情绪爆点、身份反差、揭晓和高潮尽量提炼得更集中，而不是只做平铺直叙的摘要
- 必须按自然段组织叙事；遇到时空/场景切换，或某一段以人物说话收束时，该段结尾必须明确保留至少 1 秒的停顿、反应或环境余韵，避免硬切
- **戏剧弧线强制要求**：
{drama_requirements}
【节奏参考示例】
{fewshot_examples}
输出规范：

1. **video_analysis**：分析视频的风格、主题、基调和关键元素。
   必须在 style 中说明画面风格类型（真人写实/3D CG/2D动漫等）

2. **角色定义 (characters)**：
   ✅ 只定义横跨10秒以上不同剧情中出现的重要角色，一闪而过的路人不需要定义
   ✅ description 只写【固定外观】：年龄、性别、发型、五官、服装、配饰（不要写画面风格，风格已在顶层 video_analysis.style 定义）
   ✅ voice_description 只写【固定音色属性】：音色、语速、说话风格
   ✅ personality 描述性格特点
   ❌ 禁止在 description 中描述后期/变身后/受伤后/换装后等任何非初始状态的外观，所有角色只定义最初登场时的样子
   ❌ 禁止写情绪变化（如"眼神从希望变为绝望"）、表情、动作、剧情发展（如"后期…"）
   ❌ 禁止写随剧情变化的声音情绪（如"起初平静后来愤怒"、"声音逐渐颤抖"）
   ❌ 不用知名影视IP，可用神话人物
   ⚠️ 同一角色有明显不同外观形态（如变身前后、换装后）必须作为两个独立角色分别定义

3. **场景 (locations)**：被多处共用的地点才定义，只描述环境固定特征
   ✅ 场景只要初始场景，不要中间态的场景和结尾的场景（比如，地面被砸出大坑，这个属于后续场景）
   ❌ 不要把动态变化的道具和人物等定义在环境中

4. **关键道具 (props)**：横跨10秒以上不同剧情中反复出现的重要道具（角色随身的武器、信物、魔法物品等），
   description 只写固定外观特征（形状、材质、颜色、特效），不要写画面风格。
   只出现一两秒的一次性道具不需要定义；已属于场景(locations)描述的固定物体不要重复定义

{story_arc_output_rules}
5. **narrative**：连贯的故事叙述文本，包含完整情节和对话，并把 hook、冲突、代价、转折、高潮、payoff 明确写进事件推进中"""


def build_recreate_screenplay_prompt(
    total_duration: float,
    drama_requirements: str,
    story_arc_output_rules: str,
    fewshot_examples: str,
    recreate_direction: str = "",
    source_duration: float = 0.0,
) -> str:
    """二创模式 system prompt。

    Response schema: ScreenplaySchema
    """
    duration_str = f"{total_duration:.1f}"
    recreate_direction = (recreate_direction or "").strip()

    source_duration_hint = ""
    if source_duration and source_duration > 0:
        source_duration_hint = (
            f"- 参考视频原始时长约 {source_duration:.1f} 秒，但本次二创必须以目标总时长 {duration_str} 秒为准\n"
            "- 如果目标时长更短，就压缩重复桥段和冗余铺垫，保留最强冲突、反转和情绪推进\n"
            "- 如果目标时长更长，可以补足因果链、动作承接和高潮展开，但不要松散灌水\n"
        )

    direction_block = ""
    if recreate_direction:
        direction_block = (
            "\n═══════════════════════════════════════════════════\n"
            "  用户给定的二创方向（最高优先级）\n"
            "═══════════════════════════════════════════════════\n"
            f"{recreate_direction}\n\n"
            "请把它理解为本次二创的创作指令：在保留原视频题材类型、世界观气质和视觉风格的前提下，"
            "优先朝这个方向改编剧情、角色关系、冲突和情绪推进。\n"
            "如果用户方向与原视频存在偏差，请保留题材核心，但以用户方向为主进行重构。\n"
        )

    return f"""请仔细观看这个视频，分析其**核心主题、类型风格和叙事模式**，然后基于此进行**二次创作**。
你不是在复刻这个视频，而是在做创意改编——保留相同的题材和世界观类型，但讲一个新的故事。
{direction_block}
你的任务是写一段**连贯的故事叙述文本**（narrative 字段），不是分镜脚本。
不需要拆分成场景编号，不需要镜头角度、光线等技术细节，就写成流畅的故事。

═══════════════════════════════════════════════════
  二创核心原则
═══════════════════════════════════════════════════

1. **主题一致，剧情全新**：保持相同题材类型和画面风格，创作全新剧情和角色

2. **用户需求优先**：如果用户给出了二创方向、情绪、人物关系、冲突走向或结局要求，必须优先按用户需求改编；如果用户没有额外要求，再基于原视频主题和风格自然延展

3. **角色必须原创**：禁止知名IP角色名（韩立、萧炎等），可用神话人物

4. **增强戏剧性**：根据用户需要增强反转、打脸、逆袭、悬念、情绪爆点或燃点，台词风格要符合人物身份和整体基调

═══════════════════════════════════════════════════
  叙述要求
═══════════════════════════════════════════════════
- 目标总时长约 {duration_str} 秒的视频内容量
{source_duration_hint}- 对话自然嵌入文本（陈风怒喝："你休想！"），内心独白用括号（陈风心想（...））
- 写成连贯流畅的故事，有起承转合
- 必须明确写出改编后各段之间的因果衔接、动作延续和情绪递进，避免像多个桥段生硬拼接在一起
- 不仅要有戏剧性，还要把最狠的冲突、反转和高潮写成真正的强节拍，而不是一句带过
- 必须按自然段组织叙事；遇到时空/场景切换，或某一段以人物说话收束时，该段结尾必须明确保留至少 1 秒的停顿、反应或环境余韵，避免硬切
- **戏剧弧线强制要求**：
{drama_requirements}
【节奏参考示例】
{fewshot_examples}
═══════════════════════════════════════════════════
  输出规范
═══════════════════════════════════════════════════

1. **video_analysis**：分析原视频的风格、主题、基调
2. **characters**：只定义横跨10秒以上不同剧情中出现的重要原创角色，一闪而过的路人不需要定义。
   description 只写【固定外观】（禁止情绪/表情/动作/剧情变化，不要写画面风格）。
   ❌ 禁止在 description 中描述后期/变身后/受伤后/换装后等任何非初始状态的外观，所有角色只定义最初登场时的样子。
   voice_description 只写【固定音色】（禁止随剧情变化的情绪）。
   ⚠️ 同一角色有明显不同外观形态（如变身前后、换装后）必须作为两个独立角色分别定义
3. **locations**：被多处共用的地点才定义
   ✅ 场景只要初始场景，不要中间态的场景和结尾的场景（比如，地面被砸出大坑，这个属于后续场景）
   ❌ 不要把动态变化的道具和人物等定义在环境中
4. **props**：横跨10秒以上不同剧情中反复出现的关键道具，description 只写固定外观，不要写画面风格。
   只出现一两秒的一次性道具不定义；已属于场景(locations)描述的固定物体不重复定义
{story_arc_output_rules}
5. **narrative**：连贯的故事叙述文本，包含完整情节和对话，并把 hook、冲突、代价、转折、高潮、payoff 全部落实到事件推进中

注意！！！
- 这是**二创**，剧情和角色必须是全新的！
- 优先满足用户给出的二创方向与改编要求"""
