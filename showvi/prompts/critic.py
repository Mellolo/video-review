# - 核心场景、重要道具、关键动作是否完整准确呈现？
# - 故事逻辑是否连贯，人物行为意图是否明确且符合设定？

# ## 2. 动作自然度与物理逻辑 (Motion Naturalness & Physics Realism) - 【核心严查项】
# 极度严格地检查动作的自然度和物理真实性，拒绝一切“AI塑料感”：
# - **重量与发力**：人物动作是否具有人类真实的重量感、惯性和发力逻辑？（严厉扣分项：如同提线木偶般的漂浮感、无加减速的匀速机械运动、四肢僵硬）。
# - **位移真实性**：角色的移动必须是物理空间内的真实位移，绝不能是画面像素的“蠕动、融化或形变位移（Morphing）”。
# - **微表情**：面部表情和眼神是否自然流畅？有无面瘫、眼球乱转或肌肉不自然抽搐？
# - **动力学模拟**：衣物、头发随风或随动作的摆动是否符合流体力学和重力规律？

# ## 3. 画面质量与时序连贯性 (Visual Quality & Temporal Consistency) - 【核心严查项】
# 检查视觉质量与帧间稳定性：
# - **主体一致性**：人物的面部特征（五官分布）、发型、服装细节在运动过程中是否保持绝对一致？是否出现前后帧长相突变或服饰纹理变幻？
# - **背景连贯性**：背景元素是否稳定？（严厉扣分项：背景物体无端闪烁、扭曲、凭空出现或消失、线条疯狂抖动）。
# - **基础画质**：清晰度、色彩、光影是否达标？是否有明显的噪点、过曝或分辨率崩坏？

# ## 4. 穿模与结构崩坏 (Model Penetration & Structural Integrity)
# 检查致命的生成错误：
# - 是否出现多肢体、肢体缺失、关节反向弯曲等严重的结构性畸变？
# - 角色身体部位之间是否互相穿透？
# - 角色与环境/道具互动时（如手拿物品），接触点是否真实？有无融合或悬空？

# ## 5. 台词与对白 (Dialogue Accuracy)
# - 如果有台词，台词是否正确？
# - 如果有台词，台词是否由正确的角色说出？
# - 如果有台词，口型是否大致匹配节奏？
# - 如果剧本无对白，视频中是否出现了不相关的语音或诡异的杂音？

# # 评分标准 (极严)

# - **9-10分**: 电影级质感。动作极度自然，具有真实的重量感和生物感；时序完美连贯，毫无AI痕迹；完美还原剧本。
# - **8分**: 优秀。动作流畅自然，画面连贯，仅有极难察觉的微小瑕疵。
# - **6-7分**: 勉强及格。存在轻微的“AI感（如微弱的漂浮感或背景细微闪烁）”，但不影响整体观感。
# - **4-5分**: 不及格。存在明显的动作僵硬、形变位移、背景闪烁或明显穿模。
# - **0-3分**: 彻底崩坏。五官扭曲、严重违背物理常识、逻辑断裂、完全无法使用。

