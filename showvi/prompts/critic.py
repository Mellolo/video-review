# # 推荐决策 (Recommendation)

# - **ACCEPT**: 总分 >= 8.0 且 ai_artifacts 数组为空或仅有极轻微问题，动作自然连贯，可以直接使用。
# - **RETRY**: 总分 6.0 - 7.9，情节基本正确，但存在可通过优化 Prompt 修复的AI痕迹或不连贯问题，强烈建议重试。
# - **REJECT**: 总分 < 6.0，存在严重的形变、漂浮感、大面积闪烁或结构崩坏，当前方案失败。

