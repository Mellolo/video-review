_DIMENSIONS_BLOCK = """# 评估维度（7 大维度）

请从以下 7 个维度进行评分（0-10 分），并标注关键问题的时间戳：

## 1. 动作流畅度 (motion_fluidity)
检查动画的运动质量和流畅性：
- 角色动作是否自然流畅，有无卡顿、跳帧或抽搐？
- 运动轨迹是否符合物理规律（惯性、重力、加速减速）？
- 表情变化是否连贯自然？
- 物体运动（衣物、头发、道具）是否流畅？

## 2. 角色一致性 (character_consistency)
检查角色在视频中的视觉一致性：
- 角色面部特征、发型、服装在整个视频中是否保持一致？
- 是否出现角色特征突变、闪烁或形变？
- 多角色场景中各角色是否可清晰区分？
- 角色比例是否稳定（无忽大忽小）？

## 3. 场景还原度 (scene_accuracy)
检查视频对场景描述的还原程度：
- 场景中的关键元素（地点、道具、环境）是否准确呈现？
- 角色动作是否符合场景描述的要求？
- 剧情关键节点是否完整呈现？
- 场景氛围和情绪是否到位？

## 4. 画面质量 (visual_quality)
检查基础视觉质量：
- 清晰度、色彩、光影是否达标？
- 是否有噪点、模糊、过曝或分辨率崩坏？
- 画面是否存在畸变、撕裂或色块？
- 特效和渲染质量如何？

## 5. 节奏与时间控制 (pacing_timing)
检查动画的节奏感：
- 动作节奏是否合理，有无过快或过慢？
- 镜头切换是否自然流畅？
- 关键动作的持续时间是否恰当？
- 整体节奏是否与场景氛围匹配？

## 6. 艺术表现力 (artistic_expression)
检查整体艺术水准：
- 构图和取景是否美观？
- 色彩搭配和光影氛围是否出色？
- 角色表演和情感表达是否有感染力？
- 整体视觉风格是否统一且有美感？

## 7. 模型穿模 (model_clipping)
检查3D模型之间的穿模/穿插问题：
- 角色与道具交互时是否有模型穿透（如剪刀穿过手指、武器穿过手掌）？
- 角色身体部位之间是否有异常穿插（如手臂穿入躯干、手指嵌入物体）？
- 服装、饰品与身体或环境物体是否有穿模？
- 角色与环境物体（墙壁、家具、植物等）是否有穿模？
- 道具与场景物体之间是否有穿插？"""


