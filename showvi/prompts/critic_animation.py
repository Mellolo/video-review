# ═══════════════════════════════════════════════════════════════════════════
#  Prompt 构建函数
# ═══════════════════════════════════════════════════════════════════════════

def build_animation_critique_prompt(
    scene_description: str,
    strictness: int = 3,
) -> str:
    """构建动画审核的 system prompt，注入场景描述和严格度等级。

    Args:
        scene_description: 场景描述文本
        strictness: 严格度等级 1-4（默认 3=严格）
            1=宽松, 2=普通, 3=严格, 4=极严

    Returns:
        完整的 system prompt 字符串
    """
    if strictness not in STRICTNESS_LEVELS:
        raise ValueError(
            f"无效的 strictness 等级: {strictness}，可选值: 1=宽松, 2=普通, 3=严格, 4=极严"
        )

    cfg = STRICTNESS_LEVELS[strictness]

    # 逐秒排查清单（等级 3 和 4 才有）
    if strictness >= 3:
        scan_block = f"""# 关键时间戳与问题清单

你必须在视频中逐秒排查，找出所有问题点。请标注每个问题出现的时间戳（格式: "MM:SS"），包括但不限于：
- 动作卡顿、跳帧、不自然的加速减速
- 角色特征突变、闪烁、形变
- 画面质量下降（模糊、噪点、色块、撕裂）
- 场景还原缺失或与描述不符
- 穿模、穿插、模型交互异常
- 镜头切换生硬、节奏不当
- 表情不连贯、唇形不同步
- 服装/头发/道具物理异常
- 光影不连续、色彩跳变
- 任何视觉上的不自然或瑕疵

要求：
- critical_issues 至少列出 {cfg['min_critical']} 个问题（如视频确实问题不足{cfg['min_critical']}个，也需尽力找出更多）
- minor_issues 至少列出 {cfg['min_minor']} 个问题
- 每个问题都要有精确的时间戳和具体描述"""
    else:
        scan_block = f"""# 关键时间戳与问题清单

在评估中，请标注关键问题出现的时间戳（格式: "MM:SS"），包括但不限于：
- 动作卡顿出现的时间点
- 角色特征突变的时间点
- 画面质量下降的时间点
- 场景还原缺失的时间点
- 穿模、穿插问题

要求：
- critical_issues 至少列出 {cfg['min_critical']} 个问题
- minor_issues 至少列出 {cfg['min_minor']} 个问题
- 每个问题都要有精确的时间戳和具体描述"""

    # 当无场景描述时，调整 opening 和场景描述块
    has_scene = bool(scene_description and scene_description.strip())
    opening = cfg["opening"]
    if not has_scene:
        opening = opening.replace("并与场景描述进行对比，", "直接基于视频内容本身，").replace("并与场景描述逐项对比，", "直接基于视频内容本身，")

    if has_scene:
        scene_block = f"""# 场景描述（评估对照基准）\n{scene_description}"""
    else:
        scene_block = """# 场景描述（评估对照基准）\n未提供外部场景描述。请直接基于视频画面本身进行客观质量评估，从画面内容中自主识别角色、场景、动作、道具及问题。"""

    prompt = f"""{opening}

{_DIMENSIONS_BLOCK}

{cfg['scoring_criteria']}
{cfg['scoring_note']}

{scan_block}

# 推荐决策 (recommendation)

- **ACCEPT**: 总分 >= {cfg['accept_threshold']}，问题轻微且不影响整体质量
- **RETRY**: 总分 {cfg['retry_range']}，存在需要优化修复的问题，建议重试
- **REJECT**: 总分 < {cfg['reject_threshold']}，存在严重缺陷，需要更换方案

{_JSON_FORMAT_BLOCK}

{cfg['notes']}

{scene_block}"""

    return prompt
