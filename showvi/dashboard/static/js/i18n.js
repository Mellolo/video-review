let _currentLang = localStorage.getItem('dashboard_lang') || 'zh';

/** @returns {string} current language code */
export function getCurrentLang() { return _currentLang; }

/** Set current language (also used by other modules) */
export function setCurrentLang(lang) { _currentLang = lang; }


export function t(key) {
  return I18N[_currentLang]?.[key] || I18N['en']?.[key] || key;
}

export function applyI18n() {
  document.querySelectorAll('[data-i18n]').forEach(el => {
    const val = t(el.getAttribute('data-i18n'));
    if (val.includes('<')) el.innerHTML = val;
    else el.textContent = val;
  });
  document.querySelectorAll('[data-i18n-placeholder]').forEach(el => {
    el.placeholder = t(el.getAttribute('data-i18n-placeholder'));
  });
  document.querySelectorAll('[data-i18n-title]').forEach(el => {
    el.title = t(el.getAttribute('data-i18n-title'));
  });
  const langLabel = document.getElementById('lang-label');
  if (langLabel) langLabel.textContent = _currentLang === 'zh' ? 'EN' : '中';
  document.documentElement.lang = _currentLang === 'zh' ? 'zh-CN' : 'en';
  updateProjectsToggleLabel();
}

export function getProjectDisplayName(projectName) {
  if (!projectName) return '';
  const projectMeta = window.repoData?.find(p => p.project_name === projectName);
  if (projectMeta?.storyboard_meta?.title) return projectMeta.storyboard_meta.title;
  const projectListItem = window.projectList?.find(p => p.project_name === projectName);
  if (projectListItem?.title) return projectListItem.title;
  return String(projectName).replace(/_storyboard$/, '');
}

export function updateProjectsToggleLabel() {
  const labelEl = document.getElementById('projects-toggle-label');
  const buttonEl = document.getElementById('projects-toggle');
  if (!labelEl || !buttonEl) return;
  const browseProjectName = window.monitorBrowseMode?.project || '';
  const nextLabel = browseProjectName
    ? (getProjectDisplayName(browseProjectName) || t('drawer.title'))
    : t('drawer.title');
  labelEl.textContent = nextLabel;
  buttonEl.title = browseProjectName ? `${t('drawer.title')} · ${nextLabel}` : t('drawer.title');
}

export function rerenderActiveViewForI18n() {
  updateProjectsToggleLabel();
  if (document.getElementById('view-monitor')?.classList.contains('active')) {
    window.renderMonitor();
  }
  if (document.getElementById('view-repo')?.classList.contains('active')) {
    window.renderRepoSidebar();
    if (window.activeProject) window.selectProject(window.activeProject);
  }
  if (document.getElementById('view-assets')?.classList.contains('active')) {
    window.syncAssetUploadButton();
    window.renderAssetView();
  }
}

export function toggleLang() {
  _currentLang = _currentLang === 'zh' ? 'en' : 'zh';
  localStorage.setItem('dashboard_lang', _currentLang);
  applyI18n();
  rerenderActiveViewForI18n();
}

